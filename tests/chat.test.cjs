const vm = require('node:vm');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const source = fs.readFileSync(path.join(__dirname, '../public/chat-content.js'), 'utf8');
let failSave = false, posted = [];
const ctx = vm.createContext({ Date, crypto:require('node:crypto').webcrypto, fetch:async (url,options) => { if(url.endsWith('/session')) return {ok:true,json:async()=>({csrf:'test-csrf'})}; posted.push(JSON.parse(options.body)); return {ok:!failSave,json:async()=>failSave?{error:'Please try again.'}:{saved:true}}; } });
vm.runInContext(source.replace('export const', 'const'), ctx);
const content = vm.runInContext('chatContent', ctx);
assert.equal(content.conversation.filter(q=>q.id).length,5);
const els = new Map(), documentEvents = {};
const el = id => {
  if (!els.has(id)) els.set(id,{hidden:true,value:'',textContent:'',events:{},classList:{add(){},remove(){}},setAttribute(){},querySelector(){return el('send-button');},focus(){},setCustomValidity(v){this.validity=v;},reportValidity(){},addEventListener(type,fn){this.events[type]=fn;}});
  return els.get(id);
};
ctx.document = {getElementById:el,addEventListener(type,fn){documentEvents[type]=fn;}};
vm.runInContext(fs.readFileSync(path.join(__dirname,'../public/chat.js'),'utf8').replace(/^import .*;\n/, ''),ctx);
const click = id => el(id).events.click();
(async () => {
click('talk');
assert.equal(el('chat-announcement-text').textContent,content.announcement);
assert.equal(el('chat-form').hidden,true);
assert.equal(posted.length,0);
click('chat-next');
assert.equal(el('chat-question').textContent,content.conversation[0].text);
el('chat-answer').value='My day was busy';
failSave=true;await el('chat-form').events.submit({preventDefault(){}});
assert.equal(el('chat-answer').value,'My day was busy');
const retryId=posted[0].id;failSave=false;
await el('chat-form').events.submit({preventDefault(){}});
assert.equal(posted[1].id,retryId);
assert.equal(posted[1].questionId,'day');
assert.equal(el('chat-reply').textContent,content.conversation[0].reply);
click('chat-next');
assert.equal(el('chat-form').hidden,true);
assert.equal(el('chat-question').textContent,content.conversation[1].text);
assert.equal(posted.length,2);
click('chat-next');click('chat-skip');
assert.equal(posted.length,2,'Skipping and companion chats never save');
click('chat-next');
assert.equal(el('chat-question').textContent,content.conversation[4].text);
click('chat-close');click('talk');
assert.equal(el('chat-announcement').hidden,false);
documentEvents.keydown({key:'Escape',preventDefault(){}});
assert.equal(el('chat-panel').hidden,true);
console.log('Passed: announcement first, question-only submissions, retry preserves input/ID, companion moments, skip, reopen and Escape.');
})().catch(error=>{console.error(error);process.exitCode=1;});
