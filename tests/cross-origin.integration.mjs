import assert from 'node:assert/strict';
import {chatContent} from '../public/chat-content.js';
const base='http://127.0.0.1:4180';
const origin='https://alinamato77.github.io';
const session=await fetch(base+'/api/chat/session',{headers:{Origin:origin,'Sec-Fetch-Site':'cross-site'}});
assert.equal(session.status,200);
assert.equal(session.headers.get('access-control-allow-origin'),origin);
assert.equal(session.headers.get('set-cookie'),null,'No third-party cookies required');
const {csrf,token}=await session.json();
assert.match(token,/^[a-f0-9-]{36}$/);
const preflight=await fetch(base+'/api/chat/answers',{method:'OPTIONS',headers:{Origin:origin,'Access-Control-Request-Method':'POST','Access-Control-Request-Headers':'authorization,content-type,x-bimba-csrf'}});
assert.equal(preflight.status,204);
assert.match(preflight.headers.get('access-control-allow-headers'),/Authorization/);
const foreign=await fetch(base+'/api/chat/session',{headers:{Origin:'https://untrusted.example'}});
assert.equal(foreign.status,403);
assert.equal(foreign.headers.get('access-control-allow-origin'),null);
assert.equal((await fetch(base+'/inbox',{headers:{Origin:origin}})).status,403,'Inbox access is never exposed through CORS');
const payload={id:crypto.randomUUID(),edition:chatContent.edition,name:'Local CORS test',answers:[{questionId:'mood',answer:'happy'},{questionId:'hangout',answer:'no'}]};
const headers={Origin:origin,'Content-Type':'application/json','X-Bimba-CSRF':csrf,Authorization:`Bearer ${token}`};
const post=extra=>fetch(base+'/api/chat/answers',{method:'POST',headers:{...headers,...extra},body:JSON.stringify(payload)});
assert.equal((await post({Authorization:''})).status,401);
assert.equal((await post({'X-Bimba-CSRF':'wrong'})).status,403);
assert.equal((await post()).status,201);
assert.equal((await post()).status,200,'Retry keeps the same token and submission');
const resumed=await fetch(base+'/api/chat/session',{headers:{Origin:origin,Authorization:`Bearer ${token}`}});
assert.equal((await resumed.json()).token,token);
console.log('Passed: GitHub-origin preflight/session/send/retry, no third-party cookie, rejected foreign origins and inbox CORS.');
